const fs = require('fs');

function parseCSV(text) {
  if (!text || !text.trim()) return [];
  const src = text.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const records = [];
  let fields = [];
  let field = '';
  let inQ = false;
  let i = 0;

  while (i < src.length) {
    const ch = src[i];
    const next = src[i + 1];

    if (inQ) {
      if (ch === '"' && next === '"') {
        field += '"'; i += 2; continue;
      }
      if (ch === '"') {
        inQ = false; i++; continue;
      }
      field += ch; i++; continue;
    }

    if (ch === '"') {
      inQ = true; i++; continue;
    }
    if (ch === ',') {
      fields.push(field); field = ''; i++; continue;
    }
    if (ch === '\n') {
      fields.push(field); field = '';
      records.push(fields); fields = [];
      i++; continue;
    }
    field += ch; i++;
  }
  fields.push(field);
  if (fields.some(f => f !== '')) records.push(fields);

  if (records.length < 2) return [];
  const headers = records[0].map(h => h.trim());
  const rows = [];

  for (let ri = 1; ri < records.length; ri++) {
    const rec = records[ri];
    const row = {};
    headers.forEach((h, idx) => {
      row[h] = (rec[idx] || '').trim();
    });
    if (Object.values(row).every(v => !v)) continue;
    rows.push(row);
  }
  return rows;
}

const masterRaw = fs.readFileSync('finman_2026-08-31_CAS_All_MF_merged_master_v2.csv', 'utf8');
const allRows = parseCSV(masterRaw);

const casRows = allRows.slice(28786);

console.log('Total CAS rows count:', casRows.length);

const summary = {
  total: casRows.length,
  buy_1to1_matched: 0,
  sell_breakdowns: 0,
  position_adjustments: 0,
  total_accounted: 0
};

casRows.forEach((r, idx) => {
  const t = r.InvestmentTransactionType;
  if (t === 'BUY') summary.buy_1to1_matched++;
  else if (t === 'SELL') summary.sell_breakdowns++;
  else if (t === 'UNIT_ADJUSTMENT') summary.position_adjustments++;
});

summary.total_accounted = summary.buy_1to1_matched + summary.sell_breakdowns + summary.position_adjustments;

console.log(JSON.stringify(summary, null, 2));

