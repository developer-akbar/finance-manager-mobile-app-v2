const normaliseType = (t) => {
  const s = String(t || '').trim().toLowerCase();
  if (s.startsWith('inc') || s === 'income') return 'Income';
  if (s.startsWith('trans') || s.includes('transfer')) return 'Transfer-Out';
  return 'Expense';
};

