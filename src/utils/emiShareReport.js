import { formatEmiCurrency } from './emiCalculator.js';

/**
 * Formats a clean, readable plain-text report of the EMI calculation.
 *
 * @param {Object} calculationResult - Result from calculateReducingBalanceEmi
 * @returns {string} - Formatted plain-text string
 */
export function generateEmiSummaryText(calculationResult) {
  if (!calculationResult || !calculationResult.summary) {
    return '';
  }

  const { summary, schedule, totals } = calculationResult;

  const firstDueDate = schedule && schedule.length > 0 ? schedule[0].formattedDueDate : 'N/A';
  const lastDueDate = schedule && schedule.length > 0 ? schedule[schedule.length - 1].formattedDueDate : 'N/A';

  const lines = [
    '==================================================',
    '        FINMAN — EMI CALCULATION SUMMARY',
    '==================================================',
    '',
    'LOAN OVERVIEW',
    '--------------------------------------------------',
    `Principal Amount:          ${formatEmiCurrency(summary.principal)}`,
    `Annual Interest Rate:      ${summary.annualRate}% p.a.`,
    `Loan Tenure:               ${summary.tenureDisplay}`,
    `First EMI Date:            ${firstDueDate}`,
    `Last EMI Date:             ${lastDueDate}`,
    `Base Monthly EMI:          ${formatEmiCurrency(summary.monthlyEmi)}`,
    '',
    'REPAYMENT BREAKDOWN',
    '--------------------------------------------------',
    `Total Principal:           ${formatEmiCurrency(summary.totalPrincipal)}`,
    `Total Interest:            ${formatEmiCurrency(summary.totalInterest)}`,
    summary.includeGstOnInterest
      ? `GST on Interest (${summary.gstRateInterest}%):     ${formatEmiCurrency(summary.totalGstInterest)}`
      : 'GST on Interest:           Excluded',
    `Total Repayments:          ${formatEmiCurrency(summary.totalRepayment)}`,
    '',
    'UPFRONT CHARGES',
    '--------------------------------------------------',
    `Processing Fee (Base):     ${formatEmiCurrency(summary.processingFee)}`,
    `Processing Fee GST (${summary.gstRateProcessingFee}%):  ${formatEmiCurrency(summary.processingFeeGst)}`,
    `Total Processing Fee:      ${formatEmiCurrency(summary.totalProcessingFee)}`,
    '',
    '--------------------------------------------------',
    `FINAL TOTAL AMOUNT:        ${formatEmiCurrency(summary.finalTotalAmount)}`,
    '--------------------------------------------------',
    '',
    'MONTHLY REPAYMENT SCHEDULE',
    '-----------------------------------------------------------------------------------------',
    '#    Due Date       Principal       Interest        GST (Interest)  Total Charged',
    '-----------------------------------------------------------------------------------------',
  ];

  if (Array.isArray(schedule)) {
    for (const row of schedule) {
      const numStr = String(row.month).padEnd(4, ' ');
      const dateStr = (row.formattedDueDate || row.dueDate || '').padEnd(14, ' ');
      const pStr = formatEmiCurrency(row.principal).padStart(14, ' ');
      const iStr = formatEmiCurrency(row.interest).padStart(15, ' ');
      const gStr = (row.gstOnInterest > 0 ? formatEmiCurrency(row.gstOnInterest) : '—').padStart(15, ' ');
      const tStr = formatEmiCurrency(row.totalCharged).padStart(15, ' ');
      lines.push(`${numStr} ${dateStr} ${pStr} ${iStr} ${gStr} ${tStr}`);
    }
  }

  lines.push('-----------------------------------------------------------------------------------------');
  if (totals) {
    const totP = formatEmiCurrency(totals.principal).padStart(14, ' ');
    const totI = formatEmiCurrency(totals.interest).padStart(15, ' ');
    const totG = (totals.gstOnInterest > 0 ? formatEmiCurrency(totals.gstOnInterest) : '—').padStart(15, ' ');
    const totC = formatEmiCurrency(totals.totalCharged).padStart(15, ' ');
    lines.push(`TOTAL                ${totP} ${totI} ${totG} ${totC}`);
  }
  lines.push('==================================================');
  lines.push('Generated by FinMan · Personal Financial Intelligence');

  return lines.join('\n');
}

/**
 * Copies text to the clipboard with fallback for older browsers or restricted permissions.
 *
 * @param {string} text - Text to copy
 * @returns {Promise<boolean>}
 */
export async function copyTextToClipboard(text) {
  if (!text) return false;

  // Modern Async Clipboard API
  if (navigator?.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Fallback below
    }
  }

  // Fallback: document.execCommand('copy')
  try {
    const textArea = document.createElement('textarea');
    textArea.value = text;
    textArea.style.position = 'fixed';
    textArea.style.top = '0';
    textArea.style.left = '0';
    textArea.style.opacity = '0';
    textArea.style.pointerEvents = 'none';
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    const successful = document.execCommand('copy');
    document.body.removeChild(textArea);
    return successful;
  } catch {
    return false;
  }
}

/**
 * Renders a high-resolution canvas containing a professional financial summary report.
 *
 * @param {Object} calculationResult - Result from calculateReducingBalanceEmi
 * @returns {HTMLCanvasElement|null}
 */
export function generateEmiReportCanvas(calculationResult) {
  if (typeof document === 'undefined') return null;
  if (!calculationResult || !calculationResult.summary) return null;

  const { summary, schedule, totals } = calculationResult;

  const width = 800;
  const padding = 32;
  const scheduleRows = Array.isArray(schedule) ? schedule : [];
  const rowHeight = 30;
  const tableHeaderHeight = 36;
  const tableFooterHeight = 40;
  const tableHeight = tableHeaderHeight + (scheduleRows.length * rowHeight) + tableFooterHeight;

  // Header (120) + Summary Bento (170) + Charges (80) + Table + Footer (60)
  const contentHeight = 120 + 170 + 80 + tableHeight + 70;
  const totalHeight = contentHeight + (padding * 2);

  const canvas = document.createElement('canvas');
  const dpr = Math.max(1, typeof window !== 'undefined' && window.devicePixelRatio ? window.devicePixelRatio : 2);
  canvas.width = width * dpr;
  canvas.height = totalHeight * dpr;

  const ctx = canvas.getContext('2d');
  if (!ctx) return null;

  ctx.scale(dpr, dpr);

  // Background
  ctx.fillStyle = '#0B1437';
  ctx.fillRect(0, 0, width, totalHeight);

  // Subtle border / card container
  ctx.strokeStyle = 'rgba(255, 255, 255, 0.12)';
  ctx.lineWidth = 1;
  ctx.strokeRect(10, 10, width - 20, totalHeight - 20);

  // Header Title
  ctx.fillStyle = '#00D2D3';
  ctx.font = 'bold 13px "Sora", sans-serif';
  ctx.fillText('FINMAN FINANCIAL INTELLIGENCE', padding, padding + 16);

  ctx.fillStyle = '#FFFFFF';
  ctx.font = '800 22px "Sora", sans-serif';
  ctx.fillText('EMI & Loan Repayment Schedule', padding, padding + 44);

  const dateStr = new Date().toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' });
  ctx.fillStyle = '#8FA0BC';
  ctx.font = '500 12px "Sora", sans-serif';
  ctx.fillText(`Generated on ${dateStr}`, padding, padding + 66);

  // Divider
  ctx.strokeStyle = 'rgba(255, 255, 255, 0.08)';
  ctx.beginPath();
  ctx.moveTo(padding, padding + 82);
  ctx.lineTo(width - padding, padding + 82);
  ctx.stroke();

  // Summary Bento Cards Grid (4 boxes)
  const bentoY = padding + 96;
  const cardW = (width - (padding * 2) - 36) / 4;
  const cardH = 88;

  const bentoCards = [
    { label: 'LOAN PRINCIPAL', val: formatEmiCurrency(summary.principal), sub: `${summary.annualRate}% p.a.`, color: '#FFFFFF' },
    { label: 'MONTHLY BASE EMI', val: formatEmiCurrency(summary.monthlyEmi), sub: summary.tenureDisplay, color: '#00D2D3' },
    { label: 'TOTAL INTEREST', val: formatEmiCurrency(summary.totalInterest), sub: summary.includeGstOnInterest ? `+ ${formatEmiCurrency(summary.totalGstInterest)} GST` : 'Zero GST', color: '#F59E0B' },
    { label: 'FINAL TOTAL PAYABLE', val: formatEmiCurrency(summary.finalTotalAmount), sub: 'Incl. All Fees & Taxes', color: '#00E5A0' },
  ];

  bentoCards.forEach((c, idx) => {
    const cx = padding + (idx * (cardW + 12));
    ctx.fillStyle = '#111C44';
    ctx.beginPath();
    ctx.roundRect(cx, bentoY, cardW, cardH, 8);
    ctx.fill();
    ctx.strokeStyle = 'rgba(255, 255, 255, 0.08)';
    ctx.stroke();

    ctx.fillStyle = '#8FA0BC';
    ctx.font = '700 9px "Sora", sans-serif';
    ctx.fillText(c.label, cx + 12, bentoY + 22);

    ctx.fillStyle = c.color;
    ctx.font = 'bold 15px "JetBrains Mono", monospace';
    ctx.fillText(c.val, cx + 12, bentoY + 50);

    ctx.fillStyle = '#5B6D8C';
    ctx.font = '500 10px "Sora", sans-serif';
    ctx.fillText(c.sub, cx + 12, bentoY + 72);
  });

  // Upfront Fee & Charges Summary Bar
  const feeY = bentoY + cardH + 16;
  ctx.fillStyle = '#172653';
  ctx.beginPath();
  ctx.roundRect(padding, feeY, width - (padding * 2), 40, 6);
  ctx.fill();

  ctx.fillStyle = '#A3AED0';
  ctx.font = '600 11px "Sora", sans-serif';
  ctx.fillText('Upfront Processing Fee:', padding + 16, feeY + 25);

  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 11px "JetBrains Mono", monospace';
  const feeInfo = `${formatEmiCurrency(summary.processingFee)} + ${formatEmiCurrency(summary.processingFeeGst)} (${summary.gstRateProcessingFee}% GST) = ${formatEmiCurrency(summary.totalProcessingFee)}`;
  ctx.fillText(feeInfo, padding + 170, feeY + 25);

  // Monthly Repayment Schedule Table
  const tableY = feeY + 54;
  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 13px "Sora", sans-serif';
  ctx.fillText('Monthly Repayment Schedule', padding, tableY + 16);

  const colX = [
    padding, // Month
    padding + 60, // Due Date
    padding + 220, // Principal
    padding + 360, // Interest
    padding + 500, // GST
    width - padding - 100, // Total
  ];

  // Table Header
  const thY = tableY + 30;
  ctx.fillStyle = '#172653';
  ctx.fillRect(padding, thY, width - (padding * 2), tableHeaderHeight);

  ctx.fillStyle = '#8FA0BC';
  ctx.font = '700 10px "Sora", sans-serif';
  ctx.fillText('#', colX[0] + 8, thY + 22);
  ctx.fillText('DUE DATE', colX[1], thY + 22);
  ctx.fillText('PRINCIPAL', colX[2], thY + 22);
  ctx.fillText('INTEREST', colX[3], thY + 22);
  ctx.fillText('GST (INTEREST)', colX[4], thY + 22);
  ctx.fillText('TOTAL CHARGED', colX[5], thY + 22);

  // Table Body Rows
  let curY = thY + tableHeaderHeight;
  ctx.font = '500 11px "JetBrains Mono", monospace';

  scheduleRows.forEach((row, i) => {
    if (i % 2 === 1) {
      ctx.fillStyle = 'rgba(255, 255, 255, 0.02)';
      ctx.fillRect(padding, curY, width - (padding * 2), rowHeight);
    }

    ctx.fillStyle = '#00D2D3';
    ctx.fillText(String(row.month), colX[0] + 8, curY + 20);

    ctx.fillStyle = '#FFFFFF';
    ctx.fillText(row.formattedDueDate || row.dueDate, colX[1], curY + 20);
    ctx.fillText(formatEmiCurrency(row.principal), colX[2], curY + 20);

    ctx.fillStyle = '#F59E0B';
    ctx.fillText(formatEmiCurrency(row.interest), colX[3], curY + 20);

    ctx.fillStyle = '#00D2D3';
    ctx.fillText(row.gstOnInterest > 0 ? formatEmiCurrency(row.gstOnInterest) : '—', colX[4], curY + 20);

    ctx.fillStyle = '#FFFFFF';
    ctx.fillText(formatEmiCurrency(row.totalCharged), colX[5], curY + 20);

    ctx.strokeStyle = 'rgba(255, 255, 255, 0.04)';
    ctx.beginPath();
    ctx.moveTo(padding, curY + rowHeight);
    ctx.lineTo(width - padding, curY + rowHeight);
    ctx.stroke();

    curY += rowHeight;
  });

  // Table Footer TOTAL
  ctx.fillStyle = '#172653';
  ctx.fillRect(padding, curY, width - (padding * 2), tableFooterHeight);

  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 11px "JetBrains Mono", monospace';
  ctx.fillText('TOTAL', colX[1], curY + 25);
  ctx.fillText(formatEmiCurrency(totals?.principal), colX[2], curY + 25);

  ctx.fillStyle = '#F59E0B';
  ctx.fillText(formatEmiCurrency(totals?.interest), colX[3], curY + 25);

  ctx.fillStyle = '#00D2D3';
  ctx.fillText(totals?.gstOnInterest > 0 ? formatEmiCurrency(totals?.gstOnInterest) : '—', colX[4], curY + 25);

  ctx.fillStyle = '#00E5A0';
  ctx.fillText(formatEmiCurrency(totals?.totalCharged), colX[5], curY + 25);

  // Footer branding
  const footY = curY + tableFooterHeight + 24;
  ctx.fillStyle = '#5B6D8C';
  ctx.font = '500 10px "Sora", sans-serif';
  ctx.fillText('Confidential & Private · Generated by FinMan Personal Financial Management', padding, footY);

  return canvas;
}

/**
 * Copies the report image to the clipboard as PNG. If the Clipboard API is unavailable
 * or blocked, falls back automatically to downloading the PNG image file.
 *
 * @param {HTMLCanvasElement} canvas
 * @param {string} [filename='finman-emi-schedule.png']
 * @returns {Promise<{ success: boolean, copied: boolean, downloaded: boolean, error?: string }>}
 */
export async function copyOrDownloadReportImage(canvas, filename = 'finman-emi-schedule.png') {
  if (!canvas || !canvas.toBlob) {
    return { success: false, copied: false, downloaded: false, error: 'Canvas not supported' };
  }

  return new Promise((resolve) => {
    canvas.toBlob(async (blob) => {
      if (!blob) {
        resolve({ success: false, copied: false, downloaded: false, error: 'Failed to generate PNG blob' });
        return;
      }

      // 1. Attempt ClipboardItem image write if supported
      if (
        typeof navigator !== 'undefined' &&
        navigator.clipboard &&
        typeof window !== 'undefined' &&
        window.ClipboardItem &&
        navigator.clipboard.write
      ) {
        try {
          const item = new window.ClipboardItem({ 'image/png': blob });
          await navigator.clipboard.write([item]);
          resolve({ success: true, copied: true, downloaded: false });
          return;
        } catch {
          // Fall through to download fallback
        }
      }

      // 2. Download Fallback
      try {
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = filename;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        setTimeout(() => URL.revokeObjectURL(url), 1000);
        resolve({ success: true, copied: false, downloaded: true });
      } catch (err) {
        resolve({ success: false, copied: false, downloaded: false, error: err?.message || 'Download failed' });
      }
    }, 'image/png');
  });
}

